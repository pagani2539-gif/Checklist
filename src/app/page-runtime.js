export function createPageRuntime(runtime, keys) {
  if (!runtime || !Array.isArray(keys)) throw new TypeError("A runtime object and page key list are required");
  const pageRuntime = {};
  for (const key of keys) {
    if (!Object.hasOwn(runtime, key)) throw new Error(`Page runtime is missing the required dependency "${key}"`);
    pageRuntime[key] = runtime[key];
  }
  return pageRuntime;
}
