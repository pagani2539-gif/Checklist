import assert from "node:assert/strict";
import { WIM_ELECTRONICS_DISPLAY_TYPES, sortElectronicsByCabinet, getElectronicsChecklistPages } from "../src/domain/wim-electronics-order.js";
import { makeEquipment, createInspectionRound, getItemsForSnapshot, normalizeSnapshot, getChecklistItemsProgress } from "../src/domain/master-checklist.js";
import { getChecklistPageNavigationItems } from "../src/domain/checklist-queue-state.js";
import { sortEquipmentForDisplay } from "../src/domain/ordering.js";

const system = { id: "electronics", canonicalItemId: "wim-electronics-system", scope: "IMPS", quantity: 1, active: true };
const cabinet = n => makeEquipment("CONTROL_CABINET", n, { id: `cab-${n}`, assetNo: `CAB-IMPS-${n}`, parentSystemId: system.id, scope: "IMPS" });
const equipment = [cabinet(10), cabinet(2), cabinet(1)];
for (const cab of [...equipment]) for (const [index, type] of WIM_ELECTRONICS_DISPLAY_TYPES.slice(1).entries()) equipment.push(makeEquipment(type, 1, {
  id: `${cab.id}-${type}`, assetNo: `${type}-${cab.assetNo}`, parentAssetId: cab.id, parentSystemId: system.id, scope: "IMPS", outputVoltages: [12, 48],
}));
equipment.reverse();
const before = JSON.stringify(equipment);
const sorted = sortEquipmentForDisplay(equipment);
assert.equal(JSON.stringify(equipment), before, "ordering never changes persisted records");
assert.deepEqual(sorted.slice(0, 8).map(asset => asset.type), WIM_ELECTRONICS_DISPLAY_TYPES);
assert.deepEqual(sorted.filter(asset => asset.type === "CONTROL_CABINET").map(asset => asset.id), ["cab-1", "cab-2", "cab-10"]);
assert.deepEqual(sortElectronicsByCabinet(equipment).map(asset => asset.id), sorted.map(asset => asset.id));
const profile = { id: "fixture", stationCode: "fixture", stationName: "fixture", stationFormat: "IMPS", equipment, stationSystems: [system], lanes: [], checklistConfig: {} };
const round = createInspectionRound(profile);
assert.equal(normalizeSnapshot(round.snapshot, profile).wimElectronicsInspectionVersion, "device-points-v1");
const items = getItemsForSnapshot(round.snapshot);
const navigation = getChecklistPageNavigationItems([{ code: "2.3", title: "WIM Electronics", items: items.filter(item => item.sectionCode === "2.3") }], "IMPS", round.snapshot);
const pages = getElectronicsChecklistPages(navigation, round.snapshot);
const devicePages = pages.filter(page => page.assetId);
assert.equal(devicePages.length, equipment.length, "exactly one page per physical device");
assert.deepEqual(devicePages.map(page => page.assetId), sorted.map(asset => asset.id));
for (const page of devicePages) assert(page.items.every(item => item.assetId === page.assetId));
const acdc = devicePages.find(page => page.assetId === "cab-1-WIM_AC_DC_POWER_SUPPLY");
assert(acdc.items.some(item => /-input/.test(item.id)));
assert(acdc.items.some(item => /-output/.test(item.id)));
assert.equal(acdc.items.filter(item => /-condition/.test(item.id)).length, 1);
const partialRound = { ...round, inspectionItems: { ...round.inspectionItems, [acdc.items[0].id]: { ...round.inspectionItems[acdc.items[0].id], status: "normal" } } };
assert.equal(getChecklistItemsProgress(acdc.items, partialRound).done, 1, "recording one point does not complete the entire device");
const network = devicePages.find(page => page.assetId === "cab-1-WIM_NETWORK_EQUIPMENT");
assert(!network.items.some(item => /-output/.test(item.id)), "network has no invented power output");
const phase = devicePages.find(page => page.assetId === "cab-1-WIM_PHASE_PROTECTION");
assert(!phase.items.some(item => /phase-protection-/.test(item.id)), "phase relay is a functional check, not a power output");
const switching = devicePages.find(page => page.assetId === "cab-1-WIM_SWITCHING_DC");
assert.equal(switching.items.filter(item => /switching-dc-/.test(item.id)).length, 2);
const oldSnapshot = { ...round.snapshot }; delete oldSnapshot.wimElectronicsInspectionVersion; delete oldSnapshot.evidenceCatalog;
const oldItems = getItemsForSnapshot(oldSnapshot);
assert(oldItems.some(item => item.label.includes("อุปกรณ์ควบคุมไฟฟ้าภายในตู้")), "old snapshots retain their original requirements");
assert.equal(oldItems.filter(item => item.assetId === acdc.assetId && !item.isEquipmentCleaning).length, 1);
const preserved = JSON.stringify(oldItems);
const oldPages = getElectronicsChecklistPages(oldItems, oldSnapshot);
assert.equal(JSON.stringify(oldItems), preserved);
assert.equal(oldPages.filter(page => page.assetId === acdc.assetId).length, 1);
console.log("Electronics cabinet order, device pages, inspection points and legacy preservation passed");
