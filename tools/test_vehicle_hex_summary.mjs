import assert from 'node:assert/strict';
import { buildVehicleSnapshotEvidencePages, getVehicleChartMaximum } from '../src/domain/vehicle-snapshot-evidence.js';
const rows = Array.from({length:101}, (_,i) => ({id:`d${i}`,occurredAt:'2026-10-01T09:00',reviewStatus:i===100?'incorrect':'correct'}));
rows.push({id:'n',occurredAt:'2026-10-01T22:00',reviewStatus:'unable-to-verify'});
const report={rows,supportsClassification:true};
const original=structuredClone(report);
const pages=buildVehicleSnapshotEvidencePages(report,{context:'plate'});
assert.equal(pages[0].periods.length,2);
assert.equal(pages[0].total,102);
assert.equal(pages[0].periods[0].total,101);
assert.equal(pages[0].periods[1].total,1);
assert.equal(getVehicleChartMaximum(pages[0].periods),120);
assert.equal(getVehicleChartMaximum([{groups:[{entries:Array(256)}]}]),260);
assert.equal(getVehicleChartMaximum([{groups:[{entries:[]}]}]),100);
const night=buildVehicleSnapshotEvidencePages(report,{context:'plate',scope:'night'});
assert.ok(night.every(p=>p.period.key==='night'));
assert.equal(night[0].periods,undefined);
const classification=buildVehicleSnapshotEvidencePages(report,{context:'classification'});
assert.ok(classification.every(p=>p.dimension==='classification'&&p.period.key==='day'));
assert.equal(classification.filter(p=>p.kind==='summary').length,1);
assert.ok(pages.filter(p=>p.kind==='evidence').every(p=>p.entries.length<=10));
assert.deepEqual(report,original);
console.log('PASS comparison, selected period, classification, shared scale, zero values, evidence pagination and immutable inputs');
