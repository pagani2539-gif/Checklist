import pg from 'pg';
import { performance } from 'node:perf_hooks';
import { PostgresChecklistStore } from '../server/postgres-store.mjs';
import { assertIsolatedTestDatabaseUrl } from './database_url_test_support.mjs';

// Real PostgreSQL save code, exclusively against session-local shadow tables.
export function resolveIsolatedWorkspaceDatabaseUrl(connectionString, productionConnectionString = process.env.CHECKLIST_DATABASE_URL) {
  return assertIsolatedTestDatabaseUrl(connectionString, { productionConnectionString });
}

export async function createTemporaryWorkspaceStore(state, { connectionString = process.env.CHECKLIST_POSTGRES_TEST_DATABASE_URL, version = 1 } = {}) {
  connectionString = resolveIsolatedWorkspaceDatabaseUrl(connectionString);
  const pool = new pg.Pool({ connectionString, max: 1 });
  const client = await pool.connect();
  const names = ['app_state','state_revisions','stations','lanes','assets','systems','station_tor_items','inspection_rounds','inspection_round_revisions','inspection_evidence','audit_log'];
  try {
    for (const name of names) await client.query(`CREATE TEMP TABLE ${name} AS SELECT * FROM public.${name} WITH NO DATA`);
    await client.query('ALTER TABLE pg_temp.app_state ADD COLUMN IF NOT EXISTS payload_version BIGINT');
    await client.query('CREATE TEMP TABLE workspace_operations(operation_id text PRIMARY KEY,actor_id text NOT NULL,request_hash text NOT NULL,result jsonb NOT NULL,created_at timestamptz DEFAULT NOW())');
    for (const [table, keys] of [['app_state','id'],['stations','id'],['lanes','id'],['assets','id'],['systems','id'],['station_tor_items','station_id,item_id'],['inspection_rounds','id'],['inspection_round_revisions','round_id,revision_number'],['inspection_evidence','round_id,item_id']]) await client.query(`ALTER TABLE pg_temp.${table} ADD PRIMARY KEY(${keys})`);
    for (const name of ['state_revisions','audit_log']) { await client.query(`ALTER TABLE pg_temp.${name} ALTER COLUMN id SET NOT NULL`); await client.query(`ALTER TABLE pg_temp.${name} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`); }
    const verified = await client.query('SELECT count(*)::int AS count FROM pg_class WHERE relnamespace=pg_my_temp_schema() AND relname=ANY($1::text[])', [[...names,'workspace_operations']]);
    if (verified.rows[0].count !== names.length + 1) throw Error('Temporary workspace isolation failed');
    await client.query("INSERT INTO pg_temp.app_state(id,version,payload,payload_version,updated_at) VALUES('global',$1,$2::jsonb,$1,NOW())", [version,JSON.stringify(state)]);
    await client.query("INSERT INTO pg_temp.state_revisions(state_version,payload,created_at,reason) VALUES($1,$2::jsonb,NOW(),'test-baseline')", [version,JSON.stringify(state)]);
    const queries = [];
    const timings = [];
    let tail = Promise.resolve();
    const query = async (sql,args) => { if (/\b(?:UPDATE|INSERT INTO|DELETE FROM|ALTER TABLE)\s+public\./i.test(sql)) throw Error('Production write forbidden in isolated test'); queries.push(sql); const start=performance.now(); try { return await client.query(sql,args); } finally {timings.push({sql,ms:performance.now()-start});} };
    const store = Object.create(PostgresChecklistStore.prototype);
    store.ready = Promise.resolve();
    store.pool = { query, connect: async () => { const previous = tail; let release; tail = new Promise(resolve => { release = resolve; }); await previous; return { query, release }; } };
    await store.syncProjections({ query },state,{updatedAt: new Date().toISOString(),actorId: null});
    queries.length = 0;
    timings.length = 0;
    return { store, queries, timings, query, close: async () => { await tail; client.release(); await pool.end(); } };
  } catch (error) { client.release(); await pool.end(); throw error; }
}
