import assert from "node:assert/strict";
import { getVehicleRowProgress, getVehicleRecordedProgress, isVehicleDecisionDirty, getVehiclePersistenceResult, continueAfterVehicleDecisionSave } from "../src/domain/vehicle-review-progress.js";
import { normalizeVehicleSearchState, updateVehicleSearchDimensionReview, getVehicleSearchReviewSummary } from "../src/domain/vehicle-search.js";

const dimensions = [{ statusKey: "reviewStatus" }, { statusKey: "classificationReviewStatus" }];
assert.equal(getVehicleRowProgress({}, dimensions).label, "ยังไม่ตรวจ");
assert.equal(getVehicleRowProgress({ reviewStatus: "incorrect" }, dimensions).label, "บันทึกบางส่วน");
const mixed = { reviewStatus: "incorrect", classificationReviewStatus: "unable-to-verify" };
assert.equal(getVehicleRowProgress(mixed, dimensions).recordedComplete, true);
assert.equal(getVehicleRowProgress(mixed, dimensions).verifiedComplete, false);
assert.deepEqual(getVehicleRecordedProgress([mixed, {}], dimensions), { total: 2, recordedRows: 1, remainingRows: 1, verifiedRows: 0, pendingChecks: 2, unableChecks: 1 });
assert.equal(getVehicleRecordedProgress([], dimensions).total, 0);
const detail = { correctedValue: "70-1234", correctionTarget: "plate-number", verificationScope: "", reasonCode: "blurred-image", note: "เดิม" };
const draft = { status: "incorrect", ...detail };
assert.equal(isVehicleDecisionDirty("incorrect", detail, draft), false);
for (const key of Object.keys(detail)) assert.equal(isVehicleDecisionDirty("incorrect", detail, { ...draft, [key]: "เปลี่ยน" }), true, key);
assert.equal(isVehicleDecisionDirty("incorrect", detail, { ...draft, correctedValue: " 70-1234 " }), false);
assert.equal(getVehiclePersistenceResult(null).success, false);
assert.equal(getVehiclePersistenceResult({ draftState: {} }).success, false);
assert.equal(getVehiclePersistenceResult({ version: null }).success, false);
assert.equal(getVehiclePersistenceResult({ version: 42 }).label, "บันทึกส่วนกลางแล้ว");
assert.equal(getVehiclePersistenceResult({ inspectionRounds: [], version: 2 }).label, "บันทึกลงเครื่องแล้ว");
assert.equal(getVehiclePersistenceResult({ demo: true }).label, "บันทึกในตัวอย่างแล้ว");
const original = normalizeVehicleSearchState({ rows: [{ id: "one", plateNumber: "70-1234" }] });
const reviewed = updateVehicleSearchDimensionReview(original, "one", "plate", "unable-to-verify", { verificationScope: "both-unverified", reasonCode: "blurred-image" });
assert.equal(getVehicleRecordedProgress(reviewed.rows, [dimensions[0]]).recordedRows, 1);
assert.equal(getVehicleSearchReviewSummary(reviewed, { context: "plate" }).unresolvedChecks, 1, "presentation must preserve unresolved review rules");
assert.equal(original.rows[0].reviewStatus, "pending", "original must remain unchanged");
console.log("vehicle review progress tests passed");

let finishSave;
let advanced = 0;
const waiting = continueAfterVehicleDecisionSave(() => new Promise(resolve => { finishSave = resolve; }), () => { advanced++; });
assert.equal(advanced, 0, 'must not advance before acknowledgement');
finishSave({ success: false });
await waiting;
assert.equal(advanced, 0, 'failed save must retain selected vehicle');
await continueAfterVehicleDecisionSave(async () => ({ success: true }), () => { advanced++; });
assert.equal(advanced, 1, 'successful save advances once');
await assert.rejects(continueAfterVehicleDecisionSave(async () => { throw Error('offline'); }, () => { advanced++; }), /offline/);
assert.equal(advanced, 1);
